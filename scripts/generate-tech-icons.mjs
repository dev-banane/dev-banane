import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const TECH = {
  Astro: { set: 'simple-icons', icon: 'astro', color: '#BC52EE' },
  'C++': { set: 'logos', icon: 'c-plusplus' },
  'Chrome MV3': { set: 'logos', icon: 'chrome' },
  'Cloudflare Workers': { set: 'logos', icon: 'cloudflare-workers-icon' },
  CodeMirror: { set: 'simple-icons', icon: 'codemirror', color: '#D30707' },
  D1: { set: 'logos', icon: 'cloudflare-icon' },
  Docker: { set: 'logos', icon: 'docker-icon' },
  Express: { set: 'simple-icons', icon: 'express' },
  Go: { set: 'logos', icon: 'go' },
  'IMAP / SMTP': { set: 'hugeicons', icon: 'mail-02' },
  Leaflet: { set: 'simple-icons', icon: 'leaflet', color: '#199900' },
  MongoDB: { set: 'logos', icon: 'mongodb-icon' },
  'Next.js': { set: 'simple-icons', icon: 'nextdotjs' },
  'Node.js': { set: 'logos', icon: 'nodejs-icon' },
  Postgres: { set: 'logos', icon: 'postgresql' },
  R2: { set: 'logos', icon: 'cloudflare-icon' },
  React: { set: 'logos', icon: 'react' },
  Redis: { set: 'logos', icon: 'redis' },
  'Tailwind CSS': { set: 'logos', icon: 'tailwindcss-icon' },
  TypeScript: { set: 'logos', icon: 'typescript-icon' },
  Vite: { set: 'logos', icon: 'vitejs' },
  Vue: { set: 'logos', icon: 'vue' },
  WASM: { set: 'logos', icon: 'webassembly' },
  WebSockets: { set: 'logos', icon: 'websocket', ink: '#231f20' },
  'Workers AI': { set: 'logos', icon: 'cloudflare-icon' },
  'shadcn/ui': { set: 'simple-icons', icon: 'shadcnui' },
  'three.js': { set: 'simple-icons', icon: 'threedotjs' },
  'tree-sitter': { set: 'hugeicons', icon: 'hierarchy-square-01' },
};

const sets = {};
function load(name) {
  sets[name] ??= JSON.parse(readFileSync(require.resolve(`@iconify-json/${name}/icons.json`), 'utf8'));
  return sets[name];
}

const missing = [];
const entries = Object.entries(TECH).map(([tech, { set: setName, icon, color, ink }]) => {
  const set = load(setName);
  const data = set.icons[icon] ?? set.icons[set.aliases?.[icon]?.parent];
  if (!data) {
    missing.push(`${setName}:${icon}`);
    return '';
  }
  const raw = ink ? data.body.replaceAll(ink, 'currentColor') : data.body;
  const body = raw.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const w = data.width ?? set.width ?? 24;
  const h = data.height ?? set.height ?? 24;
  const extra = color ? `, color: '${color}'` : '';
  return `  '${tech}': { body: '${body}', width: ${w}, height: ${h}${extra} },`;
});

if (missing.length) {
  console.error(`Unknown icons: ${missing.join(', ')}`);
  process.exit(1);
}

const out = `// GENERATED by scripts/generate-tech-icons.mjs, do not edit by hand.
// Sources: @iconify-json/logos, @iconify-json/simple-icons, @iconify-json/hugeicons

export type TechIconData = {
  body: string;
  width: number;
  height: number;
  color?: string;
};

export const TECH_ICONS: Record<string, TechIconData> = {
${entries.join('\n')}
};
`;

writeFileSync(join(root, 'src/lib/tech-icons.ts'), out, 'utf8');
console.log(`Wrote src/lib/tech-icons.ts with ${entries.length} tech icons.`);
